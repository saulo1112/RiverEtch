// Proof-level test: a real Groth16 proof from the build artifacts, checked by the Solidity verifier
// that snarkjs generated, on Hardhat's simulated chain. This is the exact path the dApp will use.
import { expect } from "chai";
import { network } from "hardhat";
import * as snarkjs from "snarkjs";

import { terminateSnarkjsCurve } from "../../scripts/zk/common.js";
import { requireBuiltCircuit, toVerifierArgs, type Groth16VerifierArgs } from "../helpers/zk.js";

const { ethers } = await network.create();

describe("SquareRootVerifier (generated by snarkjs)", function () {
  const circuit = requireBuiltCircuit("square_root");
  let proofArgs: Groth16VerifierArgs;

  before(async function () {
    const { proof, publicSignals } = await snarkjs.groth16.fullProve(
      { root: 3, square: 9 },
      circuit.wasm,
      circuit.zkey,
    );
    expect(publicSignals).to.deep.equal(["9"]);
    proofArgs = await toVerifierArgs(proof, publicSignals);
  });

  after(async function () {
    await terminateSnarkjsCurve();
  });

  it("accepts a valid proof for the public input it was generated for", async function () {
    const verifier = await ethers.deployContract("SquareRootVerifier");
    const [pA, pB, pC] = proofArgs;

    expect(await verifier.verifyProof(pA, pB, pC, [9n])).to.equal(true);
  });

  it("rejects the same proof for a different public input", async function () {
    const verifier = await ethers.deployContract("SquareRootVerifier");
    const [pA, pB, pC] = proofArgs;

    expect(await verifier.verifyProof(pA, pB, pC, [10n])).to.equal(false);
  });
});
