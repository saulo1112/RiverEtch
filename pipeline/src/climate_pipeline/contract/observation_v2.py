"""The observation record v2: one published scene of a reach, with estimates at declared levels.

A sibling of v1 (``contract.observation``), which stays as it is. v2 adds what the water-quality
validation v2 (D16) decides:

* two relative indices per sub-reach, NDTI and NIR/red (B8A/B04), each with its D0 z-scores; the
  verdict still follows from the NDTI z-scores alone (the trust boundary of v1);
* one estimate per target (turbidity, TSS) at a level: ``validated`` or ``estimated`` carry a
  value and an interval of known coverage, ``indicative`` a relative class only (low, medium,
  high from the station's own history), ``none`` neither;
* the model, its version and the SHA-256 of its model card, the predicted range's MdSA and the
  atmospheric correction behind the reflectance.

Conditional rules keep the record honest; ``record_sha256`` hashes the canonical JSON so a
registry can anchor the record later. The JSON Schema in
``docs/schema/observation-record.v2.schema.json`` is generated by :func:`json_schema`, and a test
fails when the two drift.
"""

from __future__ import annotations

import hashlib
import json
from typing import Any, Final, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

from climate_pipeline.contract.observation import (
    ClimateContext,
    Provenance,
    RainFlags,
    Verdict,
    ZScores,
    verdict_from_z,
)

SCHEMA_VERSION: Final = 2
SCHEMA_ID: Final = "observation-record.v2"

Level = Literal["validated", "estimated", "indicative", "none"]
Target = Literal["turbidity", "tss"]
RelativeClass = Literal["low", "medium", "high"]


class _Model(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, populate_by_name=True)


class Index(_Model):
    """One relative index per sub-reach, their mean and difference, and their D0 z-scores."""

    upstream: float | None
    downstream: float | None
    reach: float | None = Field(description="mean of the sub-reaches that were measured")
    delta: float | None = Field(description="downstream minus upstream")
    z_score: ZScores = Field(alias="zScore")


class Indices(_Model):
    """The relative indices (never a physical unit)."""

    ndti: Index
    nir_red: Index | None = Field(default=None, alias="nirRed", description="B8A/B04")


class Interval(_Model):
    """An interval around an estimate, with its nominal coverage."""

    low: float
    high: float
    coverage: float = Field(gt=0, lt=1)
    method: Literal["mondrian_split_conformal_log"]

    @model_validator(mode="after")
    def _check(self) -> Interval:
        if not 0 < self.low <= self.high:
            raise ValueError("an interval runs from a positive low to a high not below it")
        return self


class AtmosphericCorrection(_Model):
    """Which surface reflectance the estimate used."""

    processor: Literal["sen2cor"]
    collection: str
    processing_baseline: list[str] = Field(alias="processingBaseline")


class Estimate(_Model):
    """One target's estimate at a level, or why there is none."""

    target: Target
    unit: str
    level: Level
    value: float | None = None
    interval: Interval | None = None
    relative_class: RelativeClass | None = Field(default=None, alias="relativeClass")
    model_id: str | None = Field(default=None, alias="modelId")
    model_version: str | None = Field(default=None, alias="modelVersion")
    model_card_sha256: str | None = Field(default=None, alias="modelCardSha256")
    valid_range: tuple[float, float] | None = Field(default=None, alias="validRange")
    range_mdsa: float | None = Field(
        default=None, alias="rangeMdsa", description="test MdSA of the predicted range, percent"
    )
    abstain_reason: str | None = Field(default=None, alias="abstainReason")
    atmospheric_correction: AtmosphericCorrection | None = Field(
        default=None, alias="atmosphericCorrection"
    )

    @model_validator(mode="after")
    def _check(self) -> Estimate:
        quantitative = self.level in ("validated", "estimated")
        silent = not quantitative or self.abstain_reason is not None
        if silent and (self.value is not None or self.interval is not None):
            raise ValueError("only a validated or estimated level, not abstaining, has a value")
        if self.relative_class is not None and self.level != "indicative":
            raise ValueError("a relative class belongs to the indicative level only")
        if self.level == "none":
            return self
        needed = (self.model_id, self.model_version, self.model_card_sha256)
        if any(v is None for v in needed):
            raise ValueError("an estimate names its model, version and model card")
        if quantitative and self.abstain_reason is None:
            if self.value is None or self.interval is None or self.valid_range is None:
                raise ValueError("a validated or estimated level carries value, interval, range")
            if not self.interval.low <= self.value <= self.interval.high:
                raise ValueError("the value lies inside its interval")
        return self


class ObservationRecordV2(_Model):
    """One published observation of a reach (v2)."""

    schema_version: Literal[2] = Field(default=2, alias="schemaVersion")
    reach_id: str = Field(alias="reachId")
    date: str = Field(pattern=r"^\d{4}-\d{2}-\d{2}$")
    scene_id: str = Field(alias="sceneId")
    stac_item_ids: list[str] = Field(alias="stacItemIds")
    indices: Indices
    verdict: Verdict
    rain: RainFlags
    estimates: list[Estimate]
    climate_context: ClimateContext = Field(alias="climateContext")
    provenance: Provenance
    record_sha256: str | None = Field(default=None, alias="recordSha256")

    @model_validator(mode="after")
    def _check(self) -> ObservationRecordV2:
        if self.stac_item_ids != [item.id for item in self.provenance.stac_items]:
            raise ValueError("stacItemIds must list the provenance items, in order")
        if self.verdict != verdict_from_z(self.indices.ndti.z_score, self.verdict.threshold):
            raise ValueError("the verdict must follow from the NDTI D0 z-scores alone")
        targets = [e.target for e in self.estimates]
        if len(targets) != len(set(targets)):
            raise ValueError("one estimate per target")
        return self


def canonical_json(record: ObservationRecordV2) -> str:
    """The record's canonical JSON: camelCase keys, sorted, no whitespace, no hash field.

    Args:
        record: The record.

    Returns:
        The text that :func:`record_hash` hashes.
    """
    data = record.model_dump(mode="json", by_alias=True, exclude={"record_sha256"})
    return json.dumps(data, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def record_hash(record: ObservationRecordV2) -> str:
    """SHA-256 of the record's canonical JSON.

    Args:
        record: The record.

    Returns:
        The hex digest.
    """
    return hashlib.sha256(canonical_json(record).encode("utf-8")).hexdigest()


def seal(record: ObservationRecordV2) -> ObservationRecordV2:
    """The record with its ``record_sha256`` set.

    Args:
        record: The record (any hash it carries is replaced).

    Returns:
        The sealed copy.
    """
    return record.model_copy(update={"record_sha256": record_hash(record)})


def is_sealed(record: ObservationRecordV2) -> bool:
    """Whether the record's hash matches its content.

    Args:
        record: The record.

    Returns:
        True when ``record_sha256`` equals the hash of the canonical JSON.
    """
    return record.record_sha256 == record_hash(record)


def json_schema() -> dict[str, Any]:
    """The JSON Schema of the record, generated from the models, with the conditional rules.

    Returns:
        The schema (draft 2020-12).
    """
    schema = ObservationRecordV2.model_json_schema(by_alias=True, mode="validation")
    defs = schema["$defs"]
    quantitative = {"enum": ["validated", "estimated"]}
    defs["Estimate"]["allOf"] = [
        {
            "if": {"properties": {"level": {"not": quantitative}}, "required": ["level"]},
            "then": {"properties": {"value": {"const": None}, "interval": {"const": None}}},
        },
        {
            "if": {"properties": {"level": quantitative, "abstainReason": {"const": None}},
                   "required": ["level"]},
            "then": {"required": ["value", "interval", "validRange", "modelId", "modelVersion",
                                  "modelCardSha256"],
                     "properties": {"value": {"type": "number"},
                                    "interval": {"$ref": "#/$defs/Interval"}}},
        },
        {
            "if": {"properties": {"level": {"not": {"const": "indicative"}}},
                   "required": ["level"]},
            "then": {"properties": {"relativeClass": {"const": None}}},
        },
    ]  # fmt: skip
    defs["Verdict"]["allOf"] = [
        {
            "if": {"properties": {"anomalous": {"const": True}}, "required": ["anomalous"]},
            "then": {"properties": {"signals": {"minItems": 1}}},
            "else": {"properties": {"signals": {"maxItems": 0}}},
        }
    ]
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": SCHEMA_ID,
        **schema,
        "description": (
            "One published observation of a river reach (v2). Indices are relative (never a "
            "unit); an estimate shows a value and its interval only at the validated or "
            "estimated level and without an abstainReason. The verdict follows from the NDTI "
            "D0 z-scores alone."
        ),
    }


def schema_text() -> str:
    """The schema as committed: indented JSON with sorted keys and a final newline.

    Returns:
        The text of ``docs/schema/observation-record.v2.schema.json``.
    """
    return json.dumps(json_schema(), indent=2, sort_keys=True, ensure_ascii=False) + "\n"
