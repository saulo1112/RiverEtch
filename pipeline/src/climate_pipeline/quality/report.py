"""Outputs of the water-quality validation v2, the MANIFEST and its verification.

As in D15, every CSV, JSON and Markdown output is deterministic (no times, sorted keys, rounded
floats), so a recomputation from the committed snapshots matches the MANIFEST byte for byte. Run
times and library versions live in ``run.json``, outside the MANIFEST.
"""

from __future__ import annotations

import hashlib
import json
import math
import shutil
import tempfile
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from climate_pipeline.calibration.report import VERIFIED, git_blob, read_manifest, write_table
from climate_pipeline.quality.config import QualityConfig
from climate_pipeline.quality.run import Results, analyse
from climate_pipeline.screening.report import markdown_table

NOTE = (
    "Route B is a physics check: none of its values reaches a record. Indices and band ratios "
    "are relative until a level says otherwise. No output states that any actor caused anything."
)
MANIFESTS = ("acolite/dsf/manifest.csv", "acolite/radcor/manifest.csv", "mdn/manifest.csv")


def _json(data: object, path: Path) -> None:
    path.write_text(json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False,
                               default=str) + "\n", encoding="utf-8", newline="\n")  # fmt: skip


def _rounded(rows: Sequence[Mapping[str, Any]], digits: int = 3) -> list[dict[str, Any]]:
    return [
        {k: (round(v, digits) if isinstance(v, float) and math.isfinite(v) else v)
         for k, v in row.items()}
        for row in rows
    ]  # fmt: skip


def render(results: Results, cfg: QualityConfig, names: Sequence[str]) -> str:
    """``results.md``: the incomplete parts first, then each table.

    Args:
        results: Results.
        cfg: Settings.
        names: The other files written.

    Returns:
        Markdown text.
    """
    t = results.tables
    parts = [
        f"# {cfg.title}: generated results", "",
        "Generated by `climate-pipeline quality run` from the committed snapshots; do not edit by "
        "hand. Preregistration: [preregistration.md](../preregistration.md).", "",
        f"> {NOTE}", "", "## Incomplete", "",
        *([f"- {line}" for line in results.summary["incomplete"]] or ["- nothing"]), "",
    ]  # fmt: skip
    for name, title, columns in (
        ("route_a_source_check", "Route A: source check (Planetary Computer minus Earth Search)",
         ["scenes", "median_difference", "robust_sigma", "shift_sigma", "excluded"]),
        ("route_a_counts", "Route A: pairs (the Magdalena is the test set)",
         ["target", "variant", "window", "training_pairs", "training_streams", "training_stations",
          "test_pairs", "test_stations", "planetary_computer_pairs", "usgs_pairs"]),
        ("route_a_scores", "Route A: candidates and the null model",
         ["target", "variant", "candidate", "evaluation", "n", "stations", "mdsa", "sspb", "rho",
          "rho_low", "null_mdsa", "coverage80", "coverage90", "level", "product", "status"]),
        ("route_a_intervals", "Route A: interval factors (Mondrian per tercile, or pooled)",
         ["target", "variant", "candidate", "tercile", "upper_edge", "factor80", "factor90",
          "pooled"]),
        ("route_a_levels", "Route A: levels by predicted range (primary pairs)",
         ["target", "candidate", "predicted_range", "n", "rated", "mdsa", "sspb", "coverage90",
          "level"]),
        ("posthoc_scores", "v2.1 (post hoc): calibration on the Magdalena, nested LOSO",
         ["target", "variant", "window", "evaluation", "n", "stations", "mdsa", "sspb", "rho",
          "rho_low", "null_mdsa", "coverage80", "coverage90", "level", "status"]),
        ("posthoc_levels", "v2.1 (post hoc): levels by predicted range (never validated)",
         ["target", "predicted_range", "n", "rated", "mdsa", "sspb", "rho_low", "coverage90",
          "level"]),
        ("posthoc_choices", "v2.1 (post hoc): the candidate chosen for each held-out station",
         ["target", "held_out_station", "chosen"]),
        ("route_b_scores", "Route B: published and pretrained models on the same Magdalena pairs",
         ["target", "model", "correction", "n", "stations", "mdsa", "sspb", "rho", "rho_low",
          "rho_high"]),
        ("route_b_bins", "Route B: error by predicted range (a bin needs 8 pairs to be rated)",
         ["target", "model", "correction", "predicted_range", "n", "mdsa", "rated"]),
        ("route_b_adjacency", "Route B: the adjacency rule (D15's turbidity training pairs)",
         ["correction", "training_pairs", "rho", "rho_low", "rho_high", "narrow_scenes",
          "median_b11_narrow", "confirmed", "note"]),
    ):  # fmt: skip
        if t.get(name):
            parts += [f"## {title}", "", markdown_table(_rounded(t[name]), columns), ""]
    parts += ["## Files", "", *[f"- [{f}]({f})" for f in names], ""]
    return "\n".join(parts)


def write_outputs(results: Results, cfg: QualityConfig, root: Path, config: Path,
                  out: Path) -> list[Path]:  # fmt: skip
    """Write every output and the MANIFEST (the folder starts empty).

    Args:
        results: Results.
        cfg: Settings.
        root: Repository root.
        config: The settings file (hashed into the provenance).
        out: Results folder.

    Returns:
        The files written (MANIFEST last).
    """
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    written: list[Path] = []
    for name, rows in sorted(results.tables.items()):
        path = out / f"{name}.csv"
        write_table(rows, path)
        written.append(path)
    _json(results.summary, out / "summary.json")
    written.append(out / "summary.json")
    for card, suffix in [*((c, "") for c in results.cards),
                         *((c, ".posthoc") for c in results.posthoc_cards)]:  # fmt: skip
        path = out / "models" / f"{card['target']}{suffix}.json"
        path.parent.mkdir(exist_ok=True)
        _json(card, path)
        written.append(path)
    inputs = root / cfg.outputs.inputs
    provenance = {
        "preregistration_blob": git_blob(root / cfg.preregistration),
        "config_sha256": hashlib.sha256(config.read_bytes()).hexdigest(),
        "input_manifests_sha256": {
            name: hashlib.sha256((inputs / name).read_bytes()).hexdigest()
            for name in MANIFESTS
            if (inputs / name).exists()
        },
        "acolite_commit": cfg.route_b.acolite_commit,
        "mdn_commit": cfg.route_b.mdn_commit,
    }
    _json(provenance, out / "provenance.json")
    written.append(out / "provenance.json")
    names = [p.relative_to(out).as_posix() for p in written]
    md = out / "results.md"
    md.write_text(render(results, cfg, names), encoding="utf-8", newline="\n")
    written.append(md)
    lines = [
        f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.relative_to(out).as_posix()}"
        for p in sorted(written, key=lambda p: p.relative_to(out).as_posix())
    ]
    manifest = out / "MANIFEST"
    manifest.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    written.append(manifest)
    return written


def verify(cfg: QualityConfig, root: Path, config: Path) -> list[str]:
    """Recompute from the snapshots and compare CSV, JSON and Markdown with the MANIFEST.

    Args:
        cfg: Settings.
        root: Repository root.
        config: The settings file.

    Returns:
        Mismatches (empty when every verified file matches).
    """
    committed = root / cfg.outputs.results / "MANIFEST"
    if not committed.exists():
        return [f"no MANIFEST at {committed}"]
    expected = read_manifest(committed)
    with tempfile.TemporaryDirectory() as tmp:
        target = Path(tmp) / "results"
        write_outputs(analyse(cfg, root), cfg, root, config, target)
        actual = read_manifest(target / "MANIFEST")
    return [
        f"{name}: committed {expected.get(name)} recomputed {actual.get(name)}"
        for name in sorted(set(expected) | set(actual))
        if name.endswith(VERIFIED) and expected.get(name) != actual.get(name)
    ]
