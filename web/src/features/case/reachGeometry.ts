/**
 * Centre of the reach's bounding box, `[lng, lat]`: where the dive aims, the case map centres and
 * the globe's marker sits.
 */
export const REFERENCE_REACH_CENTER: LngLat = reachCenter(REFERENCE_REACH.geometry.coordinates);

function reachCenter(coordinates: readonly LngLat[]): LngLat {
  let minLng = Number.POSITIVE_INFINITY;
  let maxLng = Number.NEGATIVE_INFINITY;
  let minLat = Number.POSITIVE_INFINITY;
  let maxLat = Number.NEGATIVE_INFINITY;
  for (const [lng, lat] of coordinates) {
    minLng = Math.min(minLng, lng);
    maxLng = Math.max(maxLng, lng);
    minLat = Math.min(minLat, lat);
    maxLat = Math.max(maxLat, lat);
  }
  return [(minLng + maxLng) / 2, (minLat + maxLat) / 2];
}
